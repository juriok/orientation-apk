package si.rok.orientacija.geo

import kotlin.math.floor

/**
 * Converts GPS altitude into height above sea level.
 *
 * A satellite fix does not measure sea level. `Location.getAltitude()` returns height above
 * the WGS84 ellipsoid, a smooth mathematical figure that does not follow the Earth's actual
 * gravity field, and over Slovenia the sea-level surface sits between 44.4 m and 50.4 m
 * above it. So a raw GPS altitude reads about 47 m higher than the number printed on the
 * map for the same spot — enough to put you on the wrong contour, or to make a summit look
 * like it is not the summit.
 *
 * The separation between the two surfaces is the geoid undulation, and it varies smoothly
 * enough to tabulate: this is EGM2008 sampled on a 0.125 degree grid over Slovenia and its
 * neighbours, held as whole centimetres. Bilinear interpolation between those samples
 * reproduces the full 2.5 arc-minute model to within 0.27 m at worst and 0.05 m typically,
 * which is far below what any phone's vertical accuracy can resolve.
 *
 * Regenerate from the PROJ data grid if it ever needs extending:
 *
 * ```
 * curl -O https://cdn.proj.org/us_nga_egm08_25.tif
 * # sample at LON0 + i*STEP, LAT0 + j*STEP, write whole centimetres, rows south to north
 * ```
 *
 * Slovenia's official heights are SVS2010, referred to the Koper tide gauge, which differs
 * from EGM2008 by a few tens of centimetres. That is not worth modelling here: it is well
 * inside the noise of the altitude a phone reports in the first place.
 */
object Geoid {

    private const val LON0 = 12.0
    private const val LAT0 = 44.5
    private const val STEP = 0.125
    private const val COLUMNS = 49
    private const val ROWS = 25

    /**
     * Height above sea level, from the ellipsoidal altitude a fix carries.
     *
     * Outside the tabulated box the edge value is used rather than nothing. The undulation
     * changes by only a few metres over hundreds of kilometres, so an edge value a little
     * way outside Slovenia is still far closer to the truth than applying no correction at
     * all — which would be a 47 m error.
     */
    fun toSeaLevel(ellipsoidalMetres: Double, lat: Double, lon: Double): Double =
        ellipsoidalMetres - undulationMetres(lat, lon)

    /** How far sea level sits above the ellipsoid here, in metres. */
    fun undulationMetres(lat: Double, lon: Double): Double {
        val fx = ((lon - LON0) / STEP).coerceIn(0.0, (COLUMNS - 1).toDouble())
        val fy = ((lat - LAT0) / STEP).coerceIn(0.0, (ROWS - 1).toDouble())
        val i = floor(fx).toInt().coerceAtMost(COLUMNS - 2)
        val j = floor(fy).toInt().coerceAtMost(ROWS - 2)
        val dx = fx - i
        val dy = fy - j

        val topLeft = at(i, j)
        val topRight = at(i + 1, j)
        val bottomLeft = at(i, j + 1)
        val bottomRight = at(i + 1, j + 1)

        val south = topLeft + (topRight - topLeft) * dx
        val north = bottomLeft + (bottomRight - bottomLeft) * dx
        return (south + (north - south) * dy) / 100.0
    }

    private fun at(column: Int, row: Int): Double = table[row * COLUMNS + column].toDouble()

